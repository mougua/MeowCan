import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/**', route => route.fulfill({ json: { items: [] } }));
  await page.goto(process.env.PRACTICE_URL ?? 'http://127.0.0.1:3001');
  await page.waitForFunction(() => window.__canMusicGame?.isBootReady);
  await page.evaluate(async () => {
    const { parseVos } = await import('/src/parser/vos.ts');
    const { calculateRoundEndSec } = await import('/src/game/round-timing.ts');
    const game = window.__canMusicGame;
    game.currentSong = parseVos(await (await fetch('/songs/1.vos')).arrayBuffer());
    game.currentSongId = 1;
    game.roundEndSec = calculateRoundEndSec(game.currentSong);
    game.submissions = 0;
    game.leaderboard.submitScore = async () => { game.submissions++; };
    game.preferredAudioSource = 'procedural';
  });
  await page.locator('#btn-practice').click();
  assert.equal(await page.locator('#practice-controls').isVisible(), true);
  await page.locator('[data-practice-rate="0.5"]').click();
  await page.locator('#btn-arcade-start').click();
  await page.waitForFunction(() => window.__canMusicGame.round.state === 'playing');
  assert.equal(await page.locator('#btn-practice').isDisabled(), true);
  assert.equal(await page.evaluate(() => window.__canMusicGame.audio.getPlaybackRate()), 0.5);
  await page.locator('#btn-practice-pause').click();
  await page.evaluate(() => {
    const game = window.__canMusicGame;
    const note = game.currentSong.playableNotes.find(note => note.isLong);
    if (!note) throw new Error('Fixture requires a long note');
    game.seekPractice(note.startSec);
    game.setPracticePaused(false);
    game.handlePlayerKeyDown(note.lane);
    game.setPracticePaused(true);
    if (!note.holdActive) throw new Error('Pausing lost the active hold');
    game.setPracticePaused(false);
    if (!note.holdActive) throw new Error('Resuming lost the active hold');
    game.setPracticePaused(true);
  });
  const pausedTime = await page.evaluate(() => window.__canMusicGame.audio.getCurrentTime());
  await page.waitForTimeout(350);
  assert.equal(await page.evaluate(() => window.__canMusicGame.audio.getCurrentTime()), pausedTime);
  // Put a known note at the judgment line and drag backwards across tempo-map time.
  await page.evaluate(() => window.__canMusicGame.seekPractice(20));
  const drag = await page.evaluate(() => {
    const game = window.__canMusicGame;
    const layout = game.renderer.getLayout();
    const canvas = document.querySelector('canvas');
    const rect = canvas.getBoundingClientRect();
    const p = game.renderer.clientToScene(rect.left, rect.top);
    const q = game.renderer.clientToScene(rect.right, rect.bottom);
    return { x: rect.left + (layout.playX + layout.laneWidth * 3 - p.x) / (q.x - p.x) * rect.width,
      y: rect.top + (layout.playY + 100 - p.y) / (q.y - p.y) * rect.height };
  });
  await page.mouse.move(drag.x, drag.y);
  await page.mouse.down();
  await page.mouse.move(drag.x, drag.y - 70, { steps: 6 });
  await page.mouse.up();
  const target = await page.evaluate(() => window.__canMusicGame.audio.getCurrentTime());
  assert.ok(target < 20 && target > 0, `dragged time ${target}`);
  assert.equal(await page.locator('#btn-practice-pause').textContent(), '继续');
  assert.equal(await page.evaluate(() => window.__canMusicGame.judgment.score.missCount), 0);
  await page.locator('[data-practice-rate="1.5"]').click();
  await page.locator('#btn-practice-pause').click();
  await page.waitForTimeout(400);
  const resumed = await page.evaluate(() => window.__canMusicGame.audio.getCurrentTime());
  assert.ok(resumed - target > 0.45 && resumed - target < 0.85);
  await page.mouse.move(drag.x, drag.y);
  await page.mouse.down();
  await page.mouse.move(drag.x, drag.y + 50, { steps: 4 });
  await page.mouse.up();
  assert.equal(await page.evaluate(() => window.__canMusicGame.practicePaused), false);
  await page.locator('[data-practice-rate="0.75"]').click();
  assert.equal(await page.evaluate(() => window.__canMusicGame.audio.getPlaybackRate()), 0.75);
  await page.locator('#btn-practice-pause').click();
  await fs.mkdir('artifacts/practice', { recursive: true });
  // Choose a repeat segment using the same paused mouse-drag workflow as the UI.
  await page.evaluate(() => window.__canMusicGame.seekPractice(10));
  await page.locator('#btn-practice-loop-start').click();
  assert.equal(await page.evaluate(() => window.__canMusicGame.practicePaused), true);
  await page.evaluate(() => window.__canMusicGame.seekPractice(9));
  await page.locator('#btn-practice-loop-end').click();
  assert.match(await page.locator('#practice-loop-hint').textContent(), /终点应在起点之后/);
  assert.equal(await page.evaluate(() => window.__canMusicGame.practiceLoop.range), null);
  await page.evaluate(() => window.__canMusicGame.seekPractice(10));
  await page.mouse.move(drag.x, drag.y);
  await page.mouse.down();
  await page.mouse.move(drag.x, drag.y + 60, { steps: 5 });
  await page.mouse.up();
  const selectedEnd = await page.evaluate(() => window.__canMusicGame.audio.getCurrentTime());
  assert.ok(selectedEnd > 10);
  await page.evaluate(() => {
    const game = window.__canMusicGame;
    game.loopReturns = 0;
    const originalSeek = game.seekPractice.bind(game);
    game.seekPractice = (...args) => { game.loopReturns++; originalSeek(...args); };
  });
  await page.locator('#btn-practice-loop-end').click();
  assert.equal(await page.evaluate(() => window.__canMusicGame.practicePaused), false);
  assert.deepEqual(await page.evaluate(() => window.__canMusicGame.practiceLoop.range), { startSec: 10, endSec: selectedEnd });
  await page.waitForFunction(() => window.__canMusicGame.loopReturns >= 3);
  assert.equal(await page.evaluate(() => window.__canMusicGame.round.state), 'playing');
  await page.locator('[data-practice-rate="1.5"]').click();
  const atFastRate = await page.evaluate(() => window.__canMusicGame.loopReturns);
  await page.waitForFunction(count => window.__canMusicGame.loopReturns > count, atFastRate);
  assert.deepEqual(await page.evaluate(() => window.__canMusicGame.practiceLoop.range), { startSec: 10, endSec: selectedEnd });
  await page.locator('#btn-practice-pause').click();
  const loopPausedTime = await page.evaluate(() => window.__canMusicGame.audio.getCurrentTime());
  await page.waitForTimeout(350);
  assert.equal(await page.evaluate(() => window.__canMusicGame.audio.getCurrentTime()), loopPausedTime);
  assert.match(await page.locator('#practice-loop-range').textContent(), /已暂停/);
  await page.screenshot({ path: 'artifacts/practice/desktop.png' });
  await page.setViewportSize({ width: 1024, height: 768 });
  assert.equal(await page.locator('#btn-practice-pause').isVisible(), true);
  assert.ok(await page.locator('#btn-practice-pause').evaluate(el => el.getBoundingClientRect().width >= 100));
  assert.ok(await page.locator('#btn-practice-loop-end').evaluate(el => el.getBoundingClientRect().bottom <= innerHeight));
  await page.screenshot({ path: 'artifacts/practice/tablet.png' });
  await page.evaluate(async () => {
    const game = window.__canMusicGame;
    await game.renderer.setSkin('metallic');
    document.body.dataset.skin = 'metallic';
  });
  await page.screenshot({ path: 'artifacts/practice/metallic.png' });
  await page.locator('#btn-practice-pause').click();
  await page.locator('#btn-practice-loop-clear').click();
  assert.equal(await page.evaluate(() => window.__canMusicGame.practiceLoop.range), null);
  const afterCancelReturns = await page.evaluate(() => window.__canMusicGame.loopReturns);
  await page.waitForFunction(end => window.__canMusicGame.audio.getCurrentTime() > end + 0.1, selectedEnd);
  assert.equal(await page.evaluate(() => window.__canMusicGame.loopReturns), afterCancelReturns);
  await page.locator('#btn-practice-loop-start').click();
  await page.locator('#btn-practice-loop-clear').click();
  assert.equal(await page.evaluate(() => window.__canMusicGame.practiceLoop.startSec), null);
  await page.evaluate(() => {
    const game = window.__canMusicGame;
    game.setPracticePaused(true);
    const note = game.currentSong.playableNotes[0];
    game.seekPractice(note.startSec + 0.02, note.startSec);
    if (note.judged) throw new Error('Loop overshoot skipped the first note');
  });
  assert.equal(await page.evaluate(() => window.__canMusicGame.practicePaused), true);
  // A repeat that ends at the song's end must wrap before round completion.
  await page.evaluate(() => {
    const game = window.__canMusicGame;
    game.seekPractice(game.roundEndSec - 0.3);
  });
  await page.locator('#btn-practice-loop-start').click();
  await page.evaluate(() => window.__canMusicGame.seekPractice(window.__canMusicGame.roundEndSec));
  await page.locator('#btn-practice-loop-end').click();
  const atSongEnd = await page.evaluate(() => window.__canMusicGame.loopReturns);
  await page.waitForFunction(count => window.__canMusicGame.loopReturns > count + 1, atSongEnd);
  assert.equal(await page.evaluate(() => window.__canMusicGame.round.state), 'playing');
  await page.locator('#btn-restart').click();
  await page.waitForFunction(() => window.__canMusicGame.round.state === 'playing' && !window.__canMusicGame.isPreparingRound);
  assert.equal(await page.evaluate(() => window.__canMusicGame.practiceLoop.range), null);
  assert.equal(await page.evaluate(() => window.__canMusicGame.practiceLoop.startSec), null);
  await page.locator('#btn-arcade-abort').click();
  assert.equal(await page.evaluate(() => window.__canMusicGame.submissions), 0);
  assert.match(await page.locator('#score-save-status').textContent(), /练习成绩不计入任何排行/);
  assert.equal(await page.locator('#btn-practice').isDisabled(), false);
  await page.locator('#btn-practice').click();
  await page.locator('#btn-arcade-start').click();
  await page.waitForFunction(() => window.__canMusicGame.round.state === 'playing');
  assert.equal(await page.evaluate(() => window.__canMusicGame.audio.getPlaybackRate()), 1);
  await page.locator('#btn-arcade-abort').click();
  assert.equal(await page.evaluate(() => window.__canMusicGame.submissions), 1);
  assert.deepEqual(errors, []);
  console.log('Practice UI: transport, repeat selection, invalid endpoint, multiple repeats, cancellation, layouts, and score exclusion passed.');
} finally { await browser.close(); }
